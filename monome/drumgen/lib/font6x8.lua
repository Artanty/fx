-- Built once: char -> { column bytes }, one per column, bit 0 = top row. A
-- lowercase char shares its uppercase glyph. A char with no entry draws as a
-- blank cell, so an unexpected char is invisible rather than a wrong picture.
local COLUMNS = {}
for char, rows in pairs(ROWS) do
  -- Six columns per cell, so the advance is visible in the data: five drawn
  -- columns and a blank sixth, which is the gap between neighbouring letters.
  local columns = {}
  for col = 0, M.WIDTH - 1 do
    local bits = 0
    for row = 0, M.GLYPH_HEIGHT - 1 do
      if rows[row + 1]:sub(col + 1, col + 1) == '#' then
        bits = bits | (1 << row)
      end
    end
    columns[col + 1] = bits
  end
  COLUMNS[char] = columns
end

for char in pairs(ROWS) do
  local lower = char:lower()
  if lower ~= char then COLUMNS[lower] = COLUMNS[char] end
end

M.COLUMNS = COLUMNS

-- The pixel bits for one char, or nil if it has no glyph.
function M.glyph(char)
  return COLUMNS[char]
end

function M.has(char)
  return COLUMNS[char] ~= nil
end

-- Width in pixels of a string drawn with this font: six per char, so that a
-- 21-character line is 126px and fits 128. Callers that need to right-align or
-- centre a line should use this rather than guessing.
function M.width(text)
  return #text * M.WIDTH
end

